import { test } from "node:test";
import assert from "node:assert/strict";
import { randomUUID } from "node:crypto";
import { eq } from "drizzle-orm";
import { memberships } from "../../src/lib/db/schema";
import { withDiscoveryDatabase } from "../discovery-fixture";
import { localDiscoveryActor, prepareSample, logSample, observationSample } from "../discovery-samples";
import { discoveryQueries } from "../../src/lib/discovery/queries";
import { discoveryService } from "../../src/lib/discovery/service";
import { DiscoveryError } from "../../src/lib/discovery/contracts";
test("discovery views use persisted scoped observations, precision-aware filters and immutable identity", async () => {
  await withDiscoveryDatabase(async ({ database, actor, other, reader, campaign }) => {
    const service = discoveryService(database), queries = discoveryQueries(database), who = localDiscoveryActor(actor), a = await campaign(), b = await campaign();
    const run = await service.prepare(who, prepareSample(a.id)), log = await service.appendLog(who, logSample(run.run_id));
    const observation = observationSample(run.run_id, run.context_sha256, log.log_id, "query");
    const stored = await service.record(who, { ...observation, identity: { ...observation.identity, platform_account_id: "33333", display_name: "SYNTHETIC original" } });
    const hidden = observationSample(run.run_id, run.context_sha256, log.log_id, "query_hidden");
    await service.record(who, { ...hidden, profile: { ...hidden.profile, metrics: [{ ...hidden.profile.metrics[0], value: null, raw_display: "hidden", precision: "hidden" }] } });
    const dashboard = await queries.dashboard(reader, a.id);
    assert.equal(dashboard?.creators.length, 2); assert.equal(dashboard?.runs[0].discovered, 2); assert.equal(dashboard?.runs[0].failures, 0);
    const index = await queries.campaigns(actor), card = index.find(row => row.id === a.id);
    assert.equal(card?.creatorCount, 2); assert.equal(card?.runCount, 1); assert.equal(index.length, 2);
    assert.equal((await queries.dashboard(actor, a.id, { min: 10000, max: 13000, category: "synthetic", platform: "instagram", source: "codex_test", state: "verification_pending" }))?.creators.length, 1);
    assert.equal((await queries.dashboard(actor, a.id, { platform: "tiktok" }))?.creators.length, 0);
    assert.equal((await queries.dashboard(actor, a.id))?.counts.verified, 0);
    assert.equal(await queries.dashboard(other, a.id), null);
    assert.equal(await queries.creator(other, a.id, stored.creator_account_id), null);
    assert.equal(await queries.creator(actor, b.id, stored.creator_account_id), null);
    const renamed = observationSample(run.run_id, run.context_sha256, log.log_id, "query_renamed");
    await service.record(who, { ...renamed, identity: { ...renamed.identity, platform_account_id: "33333", display_name: "SYNTHETIC changed" } });
    const detail = await queries.creator(actor, a.id, stored.creator_account_id);
    assert.ok(detail); assert.equal(detail.account.displayName, "SYNTHETIC changed");
    assert.ok(detail.evidence.some(({ evidence }) => evidence.facts.identity?.display_name === "SYNTHETIC original"));
    const reject = (e: unknown) => e instanceof DiscoveryError && e.status === 404;
    await assert.rejects(service.reviewEvidence(who, { campaign_id: b.id, creator_account_id: stored.creator_account_id, evidence_id: stored.evidence_ids[0], verdict: "accepted", reason: "Wrong campaign" }), reject);
    await assert.rejects(service.reviewEvidence(who, { campaign_id: a.id, creator_account_id: randomUUID(), evidence_id: stored.evidence_ids[0], verdict: "accepted", reason: "Wrong account" }), reject);
    await database.delete(memberships).where(eq(memberships.userId, reader.userId));
    await assert.rejects(queries.dashboard(reader, a.id), reject);
  });
});
