import { test, expect, type Page } from "@playwright/test";
// This flow creates synthetic records. Run only against a dedicated test DB.
test.beforeAll(() => {
  if (process.env.E2E_ALLOW_WRITES !== "true") throw new Error("Use a dedicated test DB and set E2E_ALLOW_WRITES=true to run write smoke tests.");
});
async function login(page: Page) {
  await page.goto("/login");
  await page.getByLabel("이메일", { exact: true }).fill(process.env.BOOTSTRAP_EMAIL!);
  await page.getByLabel("비밀번호", { exact: true }).fill(process.env.BOOTSTRAP_PASSWORD!);
  await page.getByRole("button", { name: "로그인", exact: true }).click();
  await expect(page.getByRole("heading", { name: "좋은 연결의 시작, 프로젝트부터." })).toBeVisible();
}
test("anonymous requests redirect and invalid login displays a clear error", async ({ page }) => {
  await page.goto("/projects");
  await expect(page).toHaveURL(/\/login$/);
  await page.getByLabel("이메일", { exact: true }).fill("no-user@example.invalid");
  await page.getByLabel("비밀번호", { exact: true }).fill("synthetic-incorrect-password");
  await page.getByRole("button", { name: "로그인", exact: true }).click();
  await expect(page.locator(".form-error")).toContainText("올바르지 않습니다");
});
